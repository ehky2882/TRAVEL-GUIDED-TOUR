ONES = "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split()
TENS = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()
def two(n):
    if n < 20: return ONES[n]
    t, o = divmod(n, 10)
    return TENS[t] + ("" if o == 0 else " " + ONES[o])
def year(y):
    if 2000 <= y <= 2009: return "two thousand" + ("" if y == 2000 else " and " + ONES[y-2000])
    hi, lo = divmod(y, 100)
    if lo == 0: return two(hi) + " hundred"
    if lo < 10: return two(hi) + " oh " + ONES[lo]
    return two(hi) + " " + two(lo)

def tts(text):
    for k in sorted(RESPELL, key=len, reverse=True):
        text = re.sub(r'(?<![\w])' + re.escape(k) + r'(?![\w])', RESPELL[k], text)
    text = re.sub(r'\n?\[beat\]\n?', '\n', text)          # beat -> paragraph break
    text = re.sub(r'\b(1[0-9]{3}|20[0-9]{2})\b', lambda m: year(int(m.group())), text)
    text = re.sub(r'(?<=\w)-(?=\w)', ' ', text)             # TTS reads no hyphens
    text = text.replace('(', '').replace(')', '')
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip() + "\n"

out = pathlib.Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)
src = "\n".join(pathlib.Path(p).read_text() for p in sys.argv[2:])
for block in re.split(r'^=== ', src, flags=re.M)[1:]:
    head, body = block.split("\n", 1)
    num, slug, title = [x.strip() for x in head.split("|")]
    body = body.strip()
    clean = f"{title}\n\n{body}\n"
    t_title = tts(title).strip(); t_body = tts(body)
    safe = f"{t_title}\n\n{t_body}"
    stem = f"{num}_{slug}"
    (out / f"{stem}_clean.txt").write_text(clean)
    (out / f"{stem}_clean.md").write_text(f"# {title}\n\n{body}\n")
    (out / f"{stem}_tts-safe.txt").write_text(safe)
    (out / f"{stem}_tts-safe.md").write_text(safe)  # no markup: the TTS rules forbid it
    print(stem, len(body.replace('[beat]', '').split()), "words")
